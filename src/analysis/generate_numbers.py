            m.add("SweepGridHi", float(per.columns.max()), "{:.0f}")
            m.pct("SweepMaxSpread", float((per.max(axis=1) - per.min(axis=1)).max()), 2)
            # The reference the spread has to be judged against: how much the accuracy
            # varies between surrogates at a single chain length.  Quoting the spread
            # alone would say nothing about whether it is large.
