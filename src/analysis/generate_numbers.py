"""
COMPUTATIONAL COUPLING --- Generate the LaTeX macro file consumed by the manuscript.

Every quantity quoted in the paper is emitted here from a raw result file, so that no
number is transcribed by hand and a re-run of the experiments propagates into the text
automatically.  A missing input produces a loud placeholder (``??``) rather than a
stale value, so an unfilled number is visible in the compiled PDF.
"""

import json
import os
import sys
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "generated_numbers.tex")

MISSING = r"\textbf{??}"

# Human-facing names for the dataset keys.  Raw keys contain underscores and must
# never reach the LaTeX output.
DS_DISPLAY = {
    "celegans": r"\textit{C. elegans}",
    "drosophila_cx": r"\textit{Drosophila} CX",
    "drosophila_al": r"\textit{Drosophila} AL",
    "mouse_v1": "mouse V1",
    "human_hcp": "human HCP",
}


class Macros:
    def __init__(self) -> None:
        self.items: List[tuple] = []

    def add(self, name: str, value, fmt: str = "{}") -> None:
        # Two \newcommand lines for one name is a hard LaTeX error, and pdflatex in
        # nonstopmode reports it and then carries on with whichever definition came
        # first -- so the PDF still builds, with a number the author did not choose.
        if any(n == name for n, _ in self.items):
            raise ValueError(
                f"macro {name!r} defined twice; each number must have one source"
            )
        try:
            v = MISSING if value is None else fmt.format(value)
        except (TypeError, ValueError):
            v = MISSING
        self.items.append((name, v))

    def pval(self, name: str, value: Optional[float]) -> None:
        """A p-value in a form that never reads as zero.

        Fixed-point formatting turns anything below 0.005 into "0.00", which states
        p = 0. Below 0.001 we switch to scientific notation; at or above it, three
        decimals are enough and easier to read.
        """
        if value is None:
            self.add(name, None)
            return
        v = float(value)
        if v >= 1e-3:
            self.add(name, v, "{:.3f}")
        else:
            exp = int(np.floor(np.log10(v)))
            mant = v / (10.0 ** exp)
            self.add(name, f"{mant:.1f} \\times 10^{{{exp}}}")

    def pct(self, name: str, value: Optional[float], digits: int = 1) -> None:
        self.add(name, None if value is None else 100.0 * value, f"{{:.{digits}f}}\\%")

    def write(self, path: str, scan_dirs: Optional[List[str]] = None) -> None:
        defined = {n for n, _ in self.items}
        added = []
        if scan_dirs:
            added = sorted(self._referenced(scan_dirs) - defined)
        lines = ["% AUTO-GENERATED by src/analysis/generate_numbers.py -- do not edit.", ""]
        for name, val in self.items:
            lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")
        if added:
            lines += ["", "% Referenced by the manuscript but not available in results/;",
                      "% emitted as visible placeholders so a gap is never silent.",
                      "% \\providecommand is used so a name clash with LaTeX cannot break the build."]
            for name in added:
                lines.append(f"\\providecommand{{\\{name}}}{{{MISSING}}}")
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")
        note = (f" ({len(added)} referenced but unavailable, emitted as placeholders)"
                if added else "")
        print(f"[numbers] {len(self.items)} macros -> {path}{note}")

    # LaTeX and AMS commands that match the macro-name pattern but are not ours.
    _LATEX_RESERVED = {
        "Delta", "Theta", "Gamma", "Lambda", "Omega", "Sigma", "Pi", "Phi", "Psi",
        "Xi", "Upsilon", "Re", "Im", "Pr", "Big", "Bigg", "Large", "Huge",
        "LaTeX", "TeX", "Roman", "Alph", "Box", "Diamond", "S", "P", "O", "L",
        "Rightarrow", "Leftarrow", "Leftrightarrow", "Longrightarrow",
        "Longleftarrow", "Longleftrightarrow", "Vert", "Join", "Bumpeq",
    }

    @classmethod
    def _referenced(cls, dirs: List[str]) -> set:
        """Macro names of our naming shape that the manuscript actually uses.

        Emitting a visible placeholder for a referenced-but-unavailable number is
        safer than letting the build fail or, worse, succeed against a stale value.
        """
        import glob
        import re

        pat = re.compile(r"\\([A-Z][A-Za-z]{2,})\b")
        found = set()
        for d in dirs:
            for f in glob.glob(os.path.join(d, "*.tex")):
                with open(f) as fh:
                    for m in pat.finditer(fh.read()):
                        name = m.group(1)
                        if name not in cls._LATEX_RESERVED:
                            found.add(name)
        return found


def _sci(x: float, digits: int = 1) -> str:
    """Scientific notation as LaTeX maths, not as Python's ``4.4e-02``.

    ``{:.1e}`` inside a maths-mode macro typesets as ``4.4e - 02``, with the exponent
    read as a subtraction.  It is legible enough in a terminal to survive review and
    wrong enough in a PDF to matter.
    """
    if x == 0:
        return "0"
    exp = int(np.floor(np.log10(abs(x))))
    mant = x / (10.0 ** exp)
    return f"{mant:.{digits}f} \\times 10^{{{exp}}}"


def _read_csv(path: str) -> Optional[pd.DataFrame]:
    return pd.read_csv(path) if os.path.exists(path) else None


def _read_json(path: str) -> Optional[dict]:
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def main() -> None:
    m = Macros()

    # ---- Protocol constants (single source of truth: the config defaults) ----
    sys.path.insert(0, ROOT)
    from src.eval.reservoir import ReservoirConfig
    cfg = ReservoirConfig()
    m.add("Leak", cfg.leak, "{:.2f}")
    m.pct("FracInput", cfg.frac_input_nodes, 0)
    m.pct("FracReadout", cfg.frac_readout_nodes, 0)
    # Protocol constants are read from the code and the data that produced the results,
    # never transcribed.  A hand-copied 100 stays 100 after someone changes the default
    # to 150, and the paper then describes an experiment nobody ran.
    import inspect

    sys.path.insert(0, os.path.join(ROOT, "experiments", "ladder"))
    import run_structural_ladder as rsl

    ladder_defaults = {a.dest: a.default for a in rsl.build_parser()._actions}
    m.add("SpectralRadius", float(ladder_defaults["spectral_radius"]), "{:.2f}")
    m.add("NnodesTarget", int(rsl.N_NODES), "{}")
    m.add("SweepCount", int(ladder_defaults["sweeps"]), "{}")

    from src.tasks.shd import load_shd_cached
    shd_defaults = inspect.signature(load_shd_cached).parameters
    m.add("Tsteps", int(shd_defaults["n_steps"].default), "{}")
    m.add("Cchannels", int(shd_defaults["n_channels"].default), "{}")

    # Instance count comes from the data, so it reports what was actually run rather
    # than what the default says.
    _raw0 = _read_csv(os.path.join(RES, "ladder", "ladder_raw.csv"))
    m.add("NinstancesLadder",
          int(_raw0.groupby(["dataset", "rung"]).size().max()) if _raw0 is not None
          else int(ladder_defaults["instances"]), "{}")

    # ---- Protocol controls --------------------------------------------------
    pc = _read_json(os.path.join(RES, "ladder", "protocol_controls.json"))
    if pc:
        m.pct("ZeroRecFull", pc.get("naive_all_to_all::zero_recurrence", {}).get("mean"))
        m.pct("ZeroRecFullConn", pc.get("naive_all_to_all::connectome", {}).get("mean"))
        m.pct("ZeroRecSplit", pc.get("sensory_motor_disjoint::zero_recurrence", {}).get("mean"))
        m.pct("ZeroRecSplitConn", pc.get("sensory_motor_disjoint::connectome", {}).get("mean"))
        m.pct("ChanceLevel", pc.get("chance"))
    else:
        for k in ("ZeroRecFull", "ZeroRecFullConn", "ZeroRecSplit",
                  "ZeroRecSplitConn", "ChanceLevel"):
            m.add(k, None)

    # ---- Ladder -------------------------------------------------------------
    raw = _read_csv(os.path.join(RES, "ladder", "ladder_raw.csv"))
    ds_tag = {"celegans": "Cele", "drosophila_cx": "DrosCX", "drosophila_al": "DrosAL",
              "mouse_v1": "Mouse", "human_hcp": "Human"}
    rung_tag = {"L0_erdos_renyi": "Lzero", "L1_degree": "Lone",
                "L2_degree_valence": "Ltwo", "L3_degree_valence_motif": "Lthree",
                "L4_connectome": "Lfour"}
    if raw is not None:
        for ds, tag in ds_tag.items():
            sub = raw[raw.dataset == ds]
            for rung, rtag in rung_tag.items():
                v = sub[sub.rung == rung]["accuracy"].to_numpy()
                m.pct(f"Acc{tag}{rtag}", float(v.mean()) if len(v) else None)
                if len(v) > 1:
                    m.pct(f"Ci{tag}{rtag}", 1.96 * v.std(ddof=1) / np.sqrt(len(v)), 2)
            # Annealing quality for this dataset
            d3 = sub[sub.rung == "L3_degree_valence_motif"]
            if len(d3) and "diag_anneal_max_rel_err" in d3:
                m.pct(f"AnnealErr{tag}", float(d3["diag_anneal_max_rel_err"].mean()), 1)
                m.pct(f"AnnealConv{tag}", float(d3["diag_anneal_converged"].mean()), 0)

        # Largest absolute adjacent-rung effect anywhere in the ladder
        con = _read_csv(os.path.join(RES, "ladder", "ladder_contrasts_accuracy.csv"))
        if con is not None and len(con):
            k = con["delta"].abs().idxmax()
            m.pct("MaxLadderEffect", float(abs(con.loc[k, "delta"])), 2)
            # Dataset keys carry underscores, which LaTeX reads as subscripts and
            # which break the build outside maths mode.  Never emit a raw key.
            m.add("MaxLadderEffectWhere",
                  f"{DS_DISPLAY.get(con.loc[k, 'dataset'], con.loc[k, 'dataset'])}, "
                  f"{con.loc[k, 'property_added']}")
            m.add("NLadderContrasts", int(len(con)))
            m.add("NLadderSig", int(con["significant_holm_05"].sum()))
            # Per-property summary across networks.  The headline is not "how many of
            # 20 contrasts are significant" but "which structural property is the
            # benchmark sensitive to", and those are different questions: one property
            # can be significant in most networks while the family-wide count stays
            # small.
            prop_tag = {"+ degree sequence": "Degree",
                        "+ valence placement": "Valence",
                        "+ motif census": "Motif",
                        "Empirical connectome": "Residual"}
            for prop, ptag in prop_tag.items():
                sel = con[con.property_added == prop]
                if not len(sel):
                    continue
                m.add(f"N{ptag}Sig", int(sel["significant_holm_05"].sum()))
                m.add(f"N{ptag}Total", int(len(sel)))
                k = sel["delta"].abs().idxmax()
                m.pct(f"{ptag}EffectMax", float(sel.loc[k, "delta"]), 2)
                m.add(f"{ptag}EffectMaxG", float(sel.loc[k, "hedges_g"]), "{:+.2f}")
                m.pct(f"{ptag}EffectMedian", float(sel["delta"].median()), 2)

            # The per-property loop above supersedes the older MotifEffect* / RealEffect*
            # aliases, which the count-based framing of the results section used before
            # it was rewritten property by property.  They are not emitted: a macro file
            # full of names nothing references obscures which numbers the manuscript
            # actually depends on.

    # ---- Rate-matched ladder ------------------------------------------------
    # The matched-gain ladder leaves firing rate free, and rate both predicts accuracy
    # and sets the SynOps count, so the matched-rate re-run is what separates topology
    # from operating point.  Emitted here so the text cannot quote one without the
    # other.
    rm = _read_csv(os.path.join(RES, "ladder", "ladder_rate_matched.csv"))
    if raw is not None and "mean_rate" in raw:
        m.add("RateAccCorr", float(raw["mean_rate"].corr(raw["accuracy"])), "{:.2f}")
        l0 = raw[raw.rung == "L0_erdos_renyi"]["mean_rate"].mean()
        l4 = raw[raw.rung == "L4_connectome"]["mean_rate"].mean()
        m.add("RateRatioLzeroLfour", float(l0 / l4) if l4 else None, "{:.2f}")
        m.pct("RateLzero", float(l0), 1)
        m.pct("RateLfour", float(l4), 1)
    else:
        for k in ("RateAccCorr", "RateRatioLzeroLfour", "RateLzero", "RateLfour"):
            m.add(k, None)

    if rm is not None and len(rm):
        m.add("TargetRate", float(rm["target_rate"].iloc[0]), "{:.2f}")
        m.add("NinstancesRate", int(rm.groupby(["dataset", "rung"]).size().max()))

        # Cells whose bisection never reached the target are not rate-matched and are
        # excluded from every matched-rate statistic.  They are counted and named
        # instead, because "the calibration failed here" is itself a finding about the
        # network rather than a nuisance.
        if "calib_ok" in rm:
            ok = rm[rm.calib_ok.astype(bool)]
            bad = rm[~rm.calib_ok.astype(bool)]
        else:
            ok, bad = rm, rm.iloc[0:0]
        m.add("NRateCells", int(len(rm)))
        m.add("NRateUnmatched", int(len(bad)))
        if len(bad):
            counts = bad.dataset.value_counts()
            top = counts.index[0]
            m.add("RateUnmatchedWhere", DS_DISPLAY.get(top, top))
            m.add("NRateUnmatchedThere", int(counts.iloc[0]))
            m.pct("RateUnmatchedWorst",
                  float((bad.calib_rate / bad.target_rate).min()), 0)
        else:
            m.add("RateUnmatchedWhere", "none")
            m.add("NRateUnmatchedThere", 0)
            m.add("RateUnmatchedWorst", None)
        m.pct("RateMatchedAchieved", float(ok["mean_rate"].mean()) if len(ok) else None, 1)

        for ds, tag in ds_tag.items():
            sub = ok[ok.dataset == ds]
            for rung, rtag in rung_tag.items():
                v = sub[sub.rung == rung]["accuracy"].to_numpy()
                if len(v):
                    m.pct(f"Rm{tag}{rtag}", float(v.mean()))
                else:
                    # Every surrogate here failed to reach the target rate.  That is an
                    # exclusion with a stated reason, not a number we failed to compute,
                    # so it must not render as the missing-value marker.
                    m.add(f"Rm{tag}{rtag}", r"$\dagger$")

        # The headline contrast, computed only over networks where every rung was
        # actually matched -- a per-network gap is meaningless if one of its two rungs
        # was not calibrated.
        per = ok.groupby(["dataset", "rung"])["accuracy"].mean().unstack()
        complete = [d for d in per.index
                    if per.loc[d].notna().all()
                    and (ok[ok.dataset == d].groupby("rung").size()
                         == rm[rm.dataset == d].groupby("rung").size()).all()]
        m.add("NRateCompleteNetworks", len(complete))
        if complete:
            sub = per.loc[complete]
            spread = sub.max(axis=1) - sub.min(axis=1)
            m.pct("RmMaxSpread", float(spread.max()), 2)
            m.add("RmMaxSpreadWhere",
                  DS_DISPLAY.get(str(spread.idxmax()), str(spread.idxmax())))
            gap = sub["L0_erdos_renyi"] - sub["L4_connectome"]
            m.pct("RmLzeroMinusLfour", float(gap.max()), 2)
            m.pct("RmLzeroMinusLfourMin", float(gap.min()), 2)
            m.add("RmLzeroMinusLfourWhere",
                  DS_DISPLAY.get(str(gap.idxmax()), str(gap.idxmax())))
            # How much of the whole L0->L4 decline is already spent by imposing the
            # degree sequence.  Reported as a range over the fully matched networks
            # rather than as "almost all", which is not what the numbers say.
            first = sub["L0_erdos_renyi"] - sub["L1_degree"]
            share = (first / gap).replace([np.inf, -np.inf], np.nan).dropna()
            if len(share):
                m.pct("RmDegreeShareMin", float(share.min()), 0)
                m.pct("RmDegreeShareMax", float(share.max()), 0)
            if raw is not None:
                g = raw.groupby(["dataset", "rung"])["accuracy"].mean().unstack()
                g = g.loc[[d for d in complete if d in g.index]]
                mg = g["L0_erdos_renyi"] - g["L4_connectome"]
                m.pct("MgLzeroMinusLfour", float(mg.max()), 2)
                m.pct("MgLzeroMinusLfourMin", float(mg.min()), 2)
    else:
        for k in ("TargetRate", "NinstancesRate", "RateMatchedAchieved",
                  "RmMaxSpread", "RmMaxSpreadWhere", "RmLzeroMinusLfour",
                  "MgLzeroMinusLfour"):
            m.add(k, None)

    # ---- Null-model validation ---------------------------------------------
    nv = _read_json(os.path.join(RES, "ladder", "null_validation.json"))
    if nv:
        for ds, tag in ds_tag.items():
            d = nv.get(ds)
            if not d:
                continue
            m.pct(f"Overlap{tag}", d.get("overlap_L3"), 1)
            m.pct(f"OverlapLtwo{tag}", d.get("overlap_L2"), 1)
            m.pct(f"AnnealErr{tag}Val", d.get("max_rel_err_L3"), 1)
            m.add(f"BifanReal{tag}", d.get("bifan_real"), "{:,.0f}")
            m.add(f"BifanLthree{tag}", d.get("bifan_L3"), "{:,.0f}")
            m.add(f"BifanLtwo{tag}", d.get("bifan_L2"), "{:,.0f}")
            # Mean pairwise edge overlap between ensemble members: evidence that the
            # annealed chain explores the constraint set rather than collapsing onto
            # one corner of it.  Reported as evidence of mixing, not as a uniformity
            # guarantee -- see the discussion.
            m.pct(f"PairwiseLthree{tag}", d.get("pairwise_overlap_L3"), 1)
            m.pct(f"PairwiseLtwo{tag}", d.get("pairwise_overlap_L2"), 1)
    # Aliases used in the introduction.
    if nv and nv.get("celegans"):
        d = nv["celegans"]
        m.pct("CeleAnnealErr", d.get("max_rel_err_L3"), 1)
        m.pct("CeleOverlap", d.get("overlap_L3"), 1)
        m.pct("CeleOverlapLtwo", d.get("overlap_L2"), 1)
    else:
        for k in ("CeleAnnealErr", "CeleOverlap", "CeleOverlapLtwo"):
            m.add(k, None)

    # ---- Power --------------------------------------------------------------
    # A null result is bounded by what the design could have detected, so the minimum
    # detectable effect is emitted alongside the contrasts rather than left implicit.
    pw = _read_json(os.path.join(RES, "ladder", "power_accuracy.json"))
    if pw:
        m.add("MDEHolm", float(pw["mde_holm_worst_case"]), "{:.2f}")
        m.add("MDEUncorrected", float(pw["mde_uncorrected"]), "{:.2f}")
        m.pct("PowerLevel", float(pw["power"]), 0)
    pwd_ = _read_json(os.path.join(RES, "ladder", "power_memory_capacity.json"))
    if pwd_:
        m.add("MDEHolmDyn", float(pwd_["mde_holm_worst_case"]), "{:.2f}")

    # ---- Subcircuit extraction check ----------------------------------------
    # The ladder's largest effect is carried by the degree sequence, and three of the
    # five networks are induced subgraphs grown outward from a high-degree seed.  If
    # that sampling concentrated hubs it would inflate the very property the effect is
    # attributed to, so the ratio is measured and reported rather than argued about.
    ex = _read_csv(os.path.join(RES, "ladder", "extraction_check.csv"))
    if ex is not None and len(ex):
        m.add("NWholeNetworks", int(ex["whole_network"].sum()))
        m.add("NExtractedNetworks", int((~ex["whole_network"].astype(bool)).sum()))
        m.add("MaxCVRatio", float(ex["cv_ratio"].max()), "{:.2f}")
        sub = ex[~ex["whole_network"].astype(bool)]
        if len(sub):
            m.add("MinCVRatio", float(sub["cv_ratio"].min()), "{:.2f}")

    # ---- Dynamical probes ---------------------------------------------------
    # Same per-property summary as the task ladder, on the task-independent probes.
    # Run at 10 instances per rung rather than 15, so Holm across the same 20-contrast
    # family is correspondingly harsher; the text says so rather than reporting the
    # significance count as if the two were comparable.
    dy = _read_csv(os.path.join(RES, "ladder", "dynamics_ladder.csv"))
    if dy is not None and len(dy):
        m.add("NinstancesDyn", int(dy.groupby(["dataset", "rung"]).size().max()))
        prop_tag = {"+ degree sequence": "Degree",
                    "+ valence placement": "Valence",
                    "+ motif census": "Motif",
                    "Empirical connectome": "Residual"}
        for metric, mtag in (("memory_capacity", "Mem"), ("kernel_rank", "Kern")):
            path = os.path.join(RES, "ladder", f"ladder_contrasts_{metric}.csv")
            con_d = _read_csv(path)
            if con_d is None or not len(con_d):
                continue
            m.add(f"NDyn{mtag}Sig", int(con_d["significant_holm_05"].sum()))
            m.add(f"NDyn{mtag}Total", int(len(con_d)))
            for prop, ptag in prop_tag.items():
                sel = con_d[con_d.property_added == prop]
                if not len(sel):
                    continue
                m.add(f"Dyn{mtag}{ptag}MedG",
                      float(sel["hedges_g"].median()), "{:+.2f}")
                m.add(f"NDyn{mtag}{ptag}Neg",
                      int((sel["delta"] < 0).sum()))
            # L0 against L4 on the probe itself, which is the ordering the task result
            # is being checked against.
            per = dy.groupby(["dataset", "rung"])[metric].mean().unstack()
            if {"L0_erdos_renyi", "L4_connectome"} <= set(per.columns):
                m.add(f"Dyn{mtag}LzeroOverLfour",
                      float((per["L0_erdos_renyi"] / per["L4_connectome"]).median()),
                      "{:.2f}")
                m.add(f"NDyn{mtag}LzeroHigher",
                      int((per["L0_erdos_renyi"] > per["L4_connectome"]).sum()))
                m.add(f"NDyn{mtag}Networks", int(len(per)))

    # ---- Unit-model comparison ----------------------------------------------
    # The headline experiment: same graphs, same rewirings, same metric, two unit models.
    um = _read_json(os.path.join(RES, "ladder", "unit_model_stats.json"))
    if um:
        for unit, tag in (("rate", "Rate"), ("spiking", "Spk")):
            d = um.get(unit, {})
            m.add(f"NUnit{tag}Networks", d.get("n_networks"))
            m.add(f"NUnit{tag}Leads", d.get("n_sig_positive"))
            m.add(f"NUnit{tag}Trails", d.get("n_sig_negative"))
            m.add(f"Unit{tag}MedianDiff", d.get("median_diff"), "{:+.2f}")
            frac = um.get(f"{unit}_frac_positive_all_gains")
            if frac is not None:
                m.pct(f"Unit{tag}FracLeadsAllGains", float(frac), 0)
        m.pct("UnitDeadRate", um.get("dead_frac_rate"), 1)
        m.pct("UnitDeadSpiking", um.get("dead_frac_spiking"), 1)
        if um.get("spiking_gap_r") is not None:
            m.add("UnitSilenceGapR", um["spiking_gap_r"], "{:+.2f}")
            m.pval("UnitSilenceGapP", um["spiking_gap_p"])
            m.add("UnitSilenceGapN", um.get("spiking_gap_n"))

    umc = _read_csv(os.path.join(RES, "ladder", "unit_model_comparison.csv"))
    if umc is not None and len(umc):
        m.add("NUnitEvaluations", int(len(umc)))
        m.add("NUnitNetworks", int(umc["network"].nunique()))
        m.add("NUnitInstances", int(umc["instance"].nunique()))
        m.add("NUnitGains", int(umc["spectral_radius"].nunique()))
        cap = umc.groupby("unit_model")["memory_capacity"].mean()
        if {"rate", "spiking"} <= set(cap.index):
            m.add("UnitCapRate", float(cap["rate"]), "{:.1f}")
            m.add("UnitCapSpiking", float(cap["spiking"]), "{:.1f}")
            m.add("UnitCapRatio", float(cap["rate"] / cap["spiking"]), "{:.1f}")

    # ---- The project's own scale, counted rather than remembered -------------
    # These appear in the prose documents, where they had already drifted once: the
    # test count was two revisions old and the audit tally predated four entries.
    import re as _re
    import subprocess as _sp

    audit_path = os.path.join(ROOT, "AUDIT.md")
    if os.path.exists(audit_path):
        _a = open(audit_path).read()
        n_abc = len(_re.findall(r"^#{2,3} [ABC]\d+\.", _a, _re.M))
        n_d = len(_re.findall(r"^#{2,3} D\d*\.", _a, _re.M))
