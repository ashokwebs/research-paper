        # it has not been run. Paired significance AND the minimum detectable effect are
        # both computed at the published operating point, and the manuscript reports the
        # second whenever it reports the first.
        from scipy.stats import nct, t as _t

        n_sig, mdes, mde_frac, n_powered = 0, [], [], 0
        at_rc = ms[np.isclose(ms.spectral_radius, rc)]
        for ds, sub in at_rc.groupby("dataset"):
            a = sub[sub.rung == "L4_connectome"].sort_values("instance")
            b = sub[sub.rung == "L2_degree_valence"].sort_values("instance")
            k = min(len(a), len(b))
            if k < 3:
                continue
            d = (a["memory_capacity"].to_numpy()[:k]
                 - b["memory_capacity"].to_numpy()[:k])
            sd = float(d.std(ddof=1))
            ci = 1.96 * sd / np.sqrt(k)
            if d.mean() > ci:
                n_sig += 1
            df_, crit = k - 1, _t.ppf(0.975, k - 1)
            lo_, hi_ = 0.0, 50.0
            for _ in range(60):
                mid = 0.5 * (lo_ + hi_)
                ncp = mid / sd * np.sqrt(k) if sd > 0 else np.inf
                pw = (1 - nct.cdf(crit, df_, ncp)) + nct.cdf(-crit, df_, ncp)
                if pw < 0.8:
                    lo_ = mid
                else:
                    hi_ = mid
            mde = 0.5 * (lo_ + hi_)
            base = float(b["memory_capacity"].to_numpy()[:k].mean())
            mdes.append(mde)
            if base > 0:
                frac = mde / base
                mde_frac.append(frac)
                if frac <= 0.15:
                    n_powered += 1
        m.add("NMemAdvSigAtCritical", n_sig)
        if mdes:
            m.add("MemMDEMedian", float(np.median(mdes)), "{:.2f}")
            m.pct("MemMDEFracMedian", float(np.median(mde_frac)), 0)
            m.pct("MemMDEFracMin", float(np.min(mde_frac)), 0)
            m.add("NMemPowered", n_powered)
